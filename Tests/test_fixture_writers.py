"""A tracked fixture must not be rewritable by a stray call (#124).

`Tests/corner_model.py::save_fixture` used to save the 2x2 corner model
straight into the TRACKED `Resources/Test_files/Silk_Corner2x2.FCStd`:
no argument, no caller anywhere in the repo -- one call, and a committed
file changes underneath whoever is reviewing the diff.  It now REQUIRES an
explicit destination and REFUSES any destination inside the repository
(`corner_model.writable_destination`).

This test pins that refusal, so a later edit cannot quietly re-open the
footgun.  It is cheap on purpose: the guard decides BEFORE the model is
built, so nothing is written and no document is opened.  (The happy path
-- build and save to a scratch path -- is not exercised here: it builds
the whole 2x2 model, which is the kind of work the manual tier exists
for.)

THE OTHER WRITERS INTO `Resources/Test_files/` ARE NOT FOOTGUNS.  They
are the fixture GENERATORS: `Tests/make_demo01_fixture.py` and
`Tests/make_cornercube_fixture.py` are supposed to write their tracked
file -- that is the #56 pattern, the tracked fixture IS generated by a
script -- and `Tests/run_all.py --save` writes into the gitignored
`_inspect/` directory.  This module pins the RULE (a writer that is not
a generator may not touch a tracked path), not the generators.
"""

import os
import shutil
import tempfile

from Tests import corner_model
from Tests.mcp_harness import check


def test_save_fixture_refuses_to_write_a_tracked_path(doc):
    """`save_fixture` must refuse a missing destination and a destination
    inside the repository -- and refuse it BEFORE it builds anything."""
    errors, checks = [], []

    try:
        corner_model.save_fixture(None)
        errors.append("save_fixture(None) did not refuse: the destination "
                      "must be required, or it guesses a tracked file")
    except RuntimeError as exc:
        checks.append("save_fixture(None) refused: %s" % exc)

    tracked = corner_model.fixture_path()
    check(os.path.exists(tracked),
          "the tracked corner fixture %s is missing -- this test's subject "
          "does not exist" % tracked, errors)
    try:
        corner_model.save_fixture(tracked)
        errors.append("save_fixture(<the tracked fixture>) did not refuse: "
                      "it wrote a committed file")
    except RuntimeError as exc:
        checks.append("save_fixture(<tracked>) refused: %s" % exc)

    # A scratch path is the SANCTIONED destination: the guard must let it
    # through.  Only the guard's decision is checked here -- the build
    # itself is the manual tier's business.
    tmpdir = tempfile.mkdtemp(prefix="silk_fixture_writer_")
    try:
        scratch = os.path.join(tmpdir, "corner_model.FCStd")
        got = corner_model.writable_destination(scratch)
        check(got == os.path.abspath(scratch),
              "the guard turned a scratch path into %r, want the absolute "
              "path %r" % (got, os.path.abspath(scratch)), errors)
        checks.append("a scratch destination outside the repository is "
                      "allowed: %s" % got)
    finally:
        shutil.rmtree(tmpdir, ignore_errors=True)

    return {"pass": not errors, "errors": errors, "checks": checks}


ALL_TESTS = [
    test_save_fixture_refuses_to_write_a_tracked_path,
]
