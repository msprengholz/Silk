"""The rolling corner's EXAMPLE file is pinned.

`Resources/Test_files/Silk_CornerCube_Rolling.FCStd` is the file the owner
opens to SEE the rolling corner working: the cube corner's three surfaces,
their three blends, and the corner built with the **rolling** construction
(cut-cell 66 + the triangular member whose face is a FreeCAD fill).

The rolling construction is the DEFAULT for a 3-valent corner since #119 --
but on the owner's own model it is REFUSED (one patch's band carries two
corner cells, so the leader has no single junction corner to sit on) and the
corner falls back to the shipped construction. So the default is not visible
on that model, and this file is where it demonstrably works.

**What is pinned, and how:** the file's INVENTORY, read OFFLINE from its own
`Document.xml` (the census technique -- no FreeCAD, no GUI), so a drifted
file goes red rather than quietly changing what the owner sees. The counts are
stated once, here.

The file is GENERATED by `Tests/make_rolling_corner_fixture.py`; regenerate it
with that script rather than editing it by hand, or the geometry and this
pin will disagree.
"""

import os
import xml.etree.ElementTree as ET
import zipfile

from Tests.mcp_harness import check

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FIXTURE = os.path.join(REPO, "Resources", "Test_files",
                       "Silk_CornerCube_Rolling.FCStd")

# What the file must carry, by the object's `object_type`.
EXPECTED_INVENTORY = {
    "Edge": 9,
    "Patch": 3,
    "Blend": 3,
    "CornerBlend": 1,        # the ROLLING corner (36 poles)
    "RollingMemberFace": 1,  # the member's face, a FreeCAD fill
}


def _inventory(path):
    """The object's `object_type` counts, read from the file's own XML."""
    with zipfile.ZipFile(path) as zf:
        root = ET.fromstring(zf.read("Document.xml"))
    counts = {}
    for obj in root.find("ObjectData").findall("Object"):
        props = obj.find("Properties")
        if props is None:
            continue
        for prop in props.findall("Property"):
            if prop.get("name") != "object_type":
                continue
            for child in prop:
                if child.get("value"):
                    kind = child.get("value")
                    counts[kind] = counts.get(kind, 0) + 1
    return counts


def test_rolling_corner_fixture_carries_the_rolling_corner(doc):
    """The example file holds the rolling corner, and the pin says so."""
    errors, checks = [], []
    if not os.path.exists(FIXTURE):
        return {"pass": False,
                "errors": ["missing %s -- regenerate it with "
                           "Tests/make_rolling_corner_fixture.py"
                           % os.path.basename(FIXTURE)],
                "checks": checks}
    counts = _inventory(FIXTURE)
    checks.append("%s carries %s" % (os.path.basename(FIXTURE), counts))
    for kind, want in sorted(EXPECTED_INVENTORY.items()):
        got = counts.get(kind, 0)
        check(got == want,
              "the fixture carries %d %s object(s), the pin says %d"
              % (got, kind, want), errors)
    check("CornerBlend" in counts,
          "the fixture carries no corner at all", errors)
    return {"pass": not errors, "errors": errors, "checks": checks}
